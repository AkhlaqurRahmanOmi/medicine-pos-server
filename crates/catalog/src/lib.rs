#[cfg(test)]
mod tests {
    use super::types::{ProductSummary, ProductType, RecordStatus};
    use pos_core::ids::ProductId;
    use std::fs;
    use std::path::{Path, PathBuf};

    #[test]
    fn entities_are_generated_not_handwritten() {
        let entity_dir = Path::new("src/entity");
        let dir = if entity_dir.exists() {
            entity_dir.to_path_buf()
        } else {
            PathBuf::from("crates/catalog/src/entity")
        };
        for entry in fs::read_dir(dir).expect("read entity dir") {
            let entry = entry.expect("valid entry");
            let path = entry.path();
            if path.extension().and_then(|s| s.to_str()) == Some("rs") {
                let content = fs::read_to_string(&path).expect("read entity file");
                assert!(
                    content.contains("@generated by sea-orm-codegen"),
                    "Entity file {:?} must contain @generated by sea-orm-codegen",
                    path.file_name()
                );
            }
        }
    }

    #[test]
    fn status_is_an_enum_and_an_unknown_value_is_an_error() {
        let json = "\"pending\"";
        let status: RecordStatus = serde_json::from_str(json).unwrap();
        assert_eq!(status, RecordStatus::Pending);

        let unknown = "\"not_a_status\"";
        let res: Result<RecordStatus, _> = serde_json::from_str(unknown);
        assert!(res.is_err());

        let product_type: Result<ProductType, _> = serde_json::from_str("\"invalid_type\"");
        assert!(product_type.is_err());
    }

    #[test]
    fn reference_mrp_is_a_string_on_the_wire() {
        let summary = ProductSummary {
            id: ProductId::new_v7(),
            brand_name: "Napa".into(),
            strength: Some("500 mg".into()),
            company_name: "Beximco".into(),
            generic_name: Some("Paracetamol".into()),
            dosage_form: Some("Tablet".into()),
            product_type: ProductType::Allopathic,
            reference_unit_mrp: Some(rust_decimal::Decimal::new(120, 2)), // 1.20
            is_discontinued: false,
            status: RecordStatus::Approved,
        };
        let json = serde_json::to_string(&summary).unwrap();
        assert!(
            json.contains("\"reference_unit_mrp\":\"1.20\""),
            "MRP must be a string in JSON, got: {json}"
        );
        assert!(
            !json.contains("\"reference_unit_mrp\":1.20"),
            "MRP must not be a number in JSON"
        );
    }
}
